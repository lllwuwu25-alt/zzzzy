await page.getByRole('button',{name:'采用非冲突建议'}).click()
await page.getByRole('button',{name:'完成并整理下一题'}).click()
await page.getByText('收集箱已经整理干净').waitFor()
await page.getByRole('button',{name:'设置',exact:true}).click()
await page.getByLabel('界面动效').selectOption('reduced')
await page.getByRole('button',{name:'收集箱',exact:true}).click()
if (await page.locator('html').getAttribute('data-motion') !== 'reduced') throw new Error('Motion preference failed')
for(const width of [1024,760,390]) {
  await page.setViewportSize({width,height:950})
  await page.goto('http://127.0.0.1:5174/')
  if(width <=760) await page.getByRole('button',{name:'打开导航',exact:true}).click()
  await page.getByRole('button',{name:'设置',exact:true}).click()
  await page.waitForTimeout(150)
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2)
  if(overflow) failures.push(`horizontal overflow ${width}`)
  await page.screenshot({path:`${output}/settings-${width}.png`,fullPage:true})
}
